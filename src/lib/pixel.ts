/** 把位图合并成一条 SVG path（同一行相邻像素合成一个矩形，边缘更干净） */
export function bitmapPath(rows: Bitmap, px = 1, ox = 0, oy = 0): string {
  let d = "";
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] !== "#") {
        x++;
        continue;
      }
      let end = x;
      while (end < row.length && row[end] === "#") end++;
      d += `M${ox + x * px} ${oy + y * px}h${(end - x) * px}v${px}h${-(end - x) * px}z`;
      x = end;
    }
  });
  return d;
}

/** 一段文字（5×7 字库）→ path，返回总宽度方便居中 */
export function textPath(text: string, px: number, ox: number, oy: number, gap = 1) {
  let d = "";
  let cursor = 0;
  for (const ch of text) {
    const glyph = FONT[ch];
    if (!glyph) {
      cursor += 3 * px;
      continue;
    }
    d += bitmapPath(glyph, px, ox + cursor, oy);
    cursor += (5 + gap) * px;
  }
  return { d, width: Math.max(0, cursor - gap * px) };
}
